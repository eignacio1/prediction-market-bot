"""The rolling backlog (operator 2026-10-30 08:26 PT): one reader for 04_EXECUTION/ROLLING_BACKLOG.json.

The strategic window maintains the JSON; terminals never edit it. Two consumers read it through here, so they cannot disagree:
the Visual Dashboard panel (scripts/build_visual_dashboard_html.py) and ROLLING_BACKLOG.md (this script's CLI, never typed by hand).

    python3 scripts/rolling_backlog.py            # write 04_EXECUTION/ROLLING_BACKLOG.md
    python3 scripts/rolling_backlog.py --check    # exit 1 if the .md is not what the JSON renders to, or the JSON is invalid

Python 3.9 safe (the box).
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = "04_EXECUTION/ROLLING_BACKLOG.json"
OUT = "04_EXECUTION/ROLLING_BACKLOG.md"

# Display order of the groups. A ticket's status must be one of these; tickets keep the file's order inside a group.
GROUPS = ("NOW", "NEXT", "LATER", "PARKED", "DONE")
FIELDS = ("id", "order", "status", "lane", "rank", "title", "measure", "why", "source", "wave")


def validate(d: dict) -> dict:
    """Raise ValueError on any defect; return the parsed data with tickets grouped (file order kept inside a group)."""
    if not isinstance(d, dict):
        raise ValueError("top level is not an object")
    for k in ("as_of", "ranking", "tickets"):
        if k not in d:
            raise ValueError(f"missing {k!r}")
    if not isinstance(d["ranking"], list) or not all(isinstance(x, str) for x in d["ranking"]):
        raise ValueError("ranking must be a list of strings")
    if not isinstance(d["tickets"], list) or not d["tickets"]:
        raise ValueError("tickets must be a non-empty list")
    seen_id, seen_order = set(), set()
    for i, t in enumerate(d["tickets"]):
        if not isinstance(t, dict):
            raise ValueError(f"ticket #{i + 1} is not an object")
        for k in ("id", "order", "status", "title"):
            if k not in t:
                raise ValueError(f"ticket #{i + 1} ({t.get('id', '?')}) missing {k!r}")
        if t["status"] not in GROUPS:
            raise ValueError(f"{t['id']}: status {t['status']!r} is not one of {'/'.join(GROUPS)}")
        if not isinstance(t["order"], int) or isinstance(t["order"], bool):
            raise ValueError(f"{t['id']}: order must be an integer")
        if t["id"] in seen_id:
            raise ValueError(f"duplicate id {t['id']}")
        if t["order"] in seen_order:
            raise ValueError(f"duplicate order {t['order']} ({t['id']})")
        seen_id.add(t["id"])
        seen_order.add(t["order"])
    return d


def load(root: pathlib.Path = ROOT) -> dict:
    """{'ok': True, ...the file..., 'groups': [[status, [tickets]], ...]} or {'ok': False, 'error': str}. Never raises."""
    try:
        d = validate(json.loads((root / SRC).read_text(encoding="utf-8")))
        d["groups"] = [[g, [t for t in d["tickets"] if t["status"] == g]] for g in GROUPS]
        d["ok"] = True
        return d
    except Exception as e:  # missing file, bad JSON, bad shape: say so, never a blank page
        return {"ok": False, "error": f"{e.__class__.__name__}: {e}"}


def render_md(d: dict) -> str:
    lines = [
        "# Rolling backlog",
        "",
        "> GENERATED from `04_EXECUTION/ROLLING_BACKLOG.json` by `scripts/rolling_backlog.py`. Do not edit this file; the strategic window "
        "edits the JSON. Shown on the Visual Dashboard at `/visual`.",
        "",
        f"**As of:** {d['as_of']}",
        "",
        "**Ranking (highest first):** " + " > ".join(d["ranking"]),
        "",
    ]
    if d.get("about"):
        lines += [d["about"], ""]
    for status, tickets in d["groups"]:
        if not tickets:
            continue
        meaning = (d.get("statuses") or {}).get(status, "")
        lines += [f"## {status}" + (f" — {meaning}" if meaning else ""), ""]
        for t in tickets:
            done = status == "DONE"
            title = f"~~{t['title']}~~" if done else t["title"]
            lines.append(f"### {t['id']} · {title}")
            lines.append("")
            meta = [f"order {t['order']}"] + [f"{k}: {t[k]}" for k in ("lane", "rank", "wave") if t.get(k)]
            lines.append("- " + " · ".join(meta))
            for k in ("measure", "why", "source"):
                if t.get(k):
                    lines.append(f"- **{k}:** {t[k]}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list) -> int:
    d = load()
    if not d["ok"]:
        print(f"ROLLING_BACKLOG.json invalid: {d['error']}", file=sys.stderr)
        return 1
    text = render_md(d)
    out = ROOT / OUT
    if "--check" in argv:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            print(f"{OUT} is stale: run python3 scripts/rolling_backlog.py", file=sys.stderr)
            return 1
        print(f"{OUT} matches the JSON ({len(d['tickets'])} tickets)")
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({len(d['tickets'])} tickets, as of {d['as_of']})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
