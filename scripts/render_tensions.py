"""Render a tension register (02_ARCHITECTURE_DESIGN/TENSIONS/<sport>.toml) to <SPORT>_TENSIONS.md."""
from __future__ import annotations
import sys, tomllib
from pathlib import Path

def render(path: Path) -> str:
    d = tomllib.loads(path.read_text())
    m = d["meta"]
    out = [f"# {m['sport'].upper()} structural tensions — {m['updated']}", "", f"> {m['banner']}", "",
           f"Source of truth: `02_ARCHITECTURE_DESIGN/TENSIONS/{path.name}`; generated by `scripts/render_tensions.py`. Reviewed at every wave close (ADR-0075 §2).", ""]
    for t in d.get("tension", []):
        out += [f"## {t['id']} — {t['title']}  ·  {t['status']}", "",
                f"- **Where:** {t['where']}", f"- **Evidence:** {t['evidence']}",
                f"- **Pillar hurt:** {t['pillar']}", f"- **What would relieve it:** {t['relief']}", ""]
    return "\n".join(out)

if __name__ == "__main__":
    for p in sys.argv[1:]:
        p = Path(p)
        Path(p.parent / f"{p.stem.upper()}_TENSIONS.md").write_text(render(p))
