"""Render a seat TOML (02_ARCHITECTURE_DESIGN/SEATS/<sport>.toml) to <SPORT>_SEAT.md. Pure formatting; no judgement."""
from __future__ import annotations
import sys, tomllib
from pathlib import Path

def render(path: Path) -> str:
    d = tomllib.loads(path.read_text())
    m = d["meta"]
    out = [f"# {m['sport'].upper()} seat — {m['version']}", "", f"> {m['banner']}", "",
           f"Source of truth: `02_ARCHITECTURE_DESIGN/SEATS/{path.name}`. This file is generated by `scripts/render_seat.py`; edit the TOML.", ""]
    out += ["## Factors", "", "| id | class | factor | free source / field | engine slot | stage | evidence |", "|---|---|---|---|---|---|---|"]
    for f in d.get("factor", []):
        out.append(f"| {f['id']} | {f['factor_class']} | {f['name']} | {f['source']} | {f['engine_slot']} | {f['stage']} | `{f['evidence']}` |")
    out += ["", "## Cells", "", "| market | band | registry status | serving model | factors conditioned on |", "|---|---|---|---|---|"]
    for c in d.get("cell", []):
        out.append(f"| {c['market']} | {c['band']} | {c['status']} | {c['serving_model']} | {', '.join(c['factors']) or '—'} |")
    return "\n".join(out) + "\n"

if __name__ == "__main__":
    for p in sys.argv[1:]:
        p = Path(p)
        Path(p.parent / f"{p.stem.upper()}_SEAT.md").write_text(render(p))
