#!/usr/bin/env python3
"""W80P.4: MLB 2026 season look-back -- one read, cell by cell, of what each MLB arm's own rule allows to be said.

Run ONCE, by whoever closes the season, on the box after the last World Series game has settled:

    cd /opt/prediction-market-bot && PYTHONPATH=src venv/bin/python scripts/mlb_season_lookback.py \
        --out 05_RESEARCH_EXPERIMENTS/RESULTS_SUMMARIES/MLB_2026_SEASON_LOOKBACK_FINAL.md

It is not a running component (no cron, no service). Read-only on every ledger; writes only --out.
It invents no scoring rule. Each cell is read by the module that already implements its pre-registration:

  * MLB game markets (moneyline / run line / total / team total x T1/T2/T3; the 2026 postseason arm) --
    calibration_engine, policy "MLB" = EXP-037 MLB (2026-10-02): 2026 rows are NEVER scored (counted only);
    judged looks are 2027 regular season, n = 150 then 600 settled games. Counts + seal status only.
  * MLB player hits T1/T2/T3 (SHADOW / paper books) and T4M-PROJ (ACTIVE) -- run_power_calc (APR-0024: per-band
    clean_n vs variance-derived n*, 95% power, one-sided alpha 0.05). T4M-PROJ counts CONFIRMED_FILLED rows only
    (GG-527). Reaching n* is the sample-adequacy gate; it is reported as such, never as an edge verdict (G6 also
    needs DS sign-off, ADR-0005).
  * Execution E1-E3 -- distance_to_optimum.execution (fills from logs/*fill_status.jsonl; paper rows are not
    execution evidence, GG-527).

A source that cannot be read is printed as UNAVAILABLE with the reason; nothing is filled in.
"""
from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]

# The governing text per MLB cell family (paths are repo-relative; the reader opens them, not this script).
PREREGS = {
    "game": ("05_RESEARCH_EXPERIMENTS/EXP037_MLB_PREGAME_SHADOW_PREREGISTRATION_2026-10-02.md",
             "judged n = settled 2027 regular-season games with >=1 scored row; looks 150 / 600; 2026 rows never scored"),
    "hits_pregame": ("APR-0024 per-band n* (run_power_calc.py); offline model: "
                     "05_RESEARCH_EXPERIMENTS/RESULTS_SUMMARIES/EXP028_pregame_mlb_hits_RESULTS_2026-09-30.md",
                     "clean_n >= n* (variance-derived, 95% power, one-sided alpha 0.05)"),
    "t4m_proj": ("APR-0024 per-band n* (run_power_calc.py) + G6 (CLAUDE.md, ADR-0005); GG-527 fills only",
                 "clean_n (CONFIRMED_FILLED) >= n*"),
}


def _src() -> None:
    for p in (str(REPO / "src"), str(REPO / "scripts")):
        if p not in sys.path:
            sys.path.insert(0, p)


def game_cells(repo: Path) -> dict:
    """EXP-037 MLB cells from the calibration engine (counts + seal status; persist=False, writes nothing)."""
    _src()
    try:
        from prediction_market_bot.pregame_shadow import calibration_engine as ce
        res = ce.run(repo, persist=False)
    except Exception as e:  # noqa: BLE001 - reported, not hidden
        return {"error": f"{type(e).__name__}: {e}"}
    cells = [c for c in res["cells"] if c.get("sport") == "MLB"]
    return {"generated": res.get("generated"), "cells": [
        {"cell": c["cell"], "band": c.get("band"), "rows": c.get("rows", 0), "settled_games": c.get("settled_games", 0),
         "status": c.get("status_text") or c.get("status"), "verdict": c.get("verdict")} for c in cells]}


def power(repo: Path, portfolio: Path, t4_ledger: Path) -> dict:
    _src()
    try:
        import run_power_calc as rpc
        return {"bands": rpc.run_all_bands(portfolio, t4_ledger, 0.05, 0.95),
                "sources": f"{portfolio} + {t4_ledger}"}
    except Exception as e:  # noqa: BLE001
        return {"error": f"{type(e).__name__}: {e}", "sources": f"{portfolio} + {t4_ledger}"}


def execution(repo: Path) -> dict:
    _src()
    try:
        import distance_to_optimum as dto
        return {"measures": dto.execution(repo)}
    except Exception as e:  # noqa: BLE001
        return {"error": f"{type(e).__name__}: {e}"}


def _power_line(band: str, r: dict) -> str:
    st = r.get("status")
    base = f"raw_n {r.get('raw_n')} · clean_n {r.get('clean_n')}"
    if st == "COMPUTED":
        mu = r.get("mean_pnl_per_bet")
        reached = "**n* REACHED** (sample-adequacy gate met; not an edge verdict -- G6 also needs DS sign-off)" \
            if r.get("met") else f"below n* (gap {r.get('gap_to_n_star')}; ETA {r.get('eta_weeks') and round(r['eta_weeks'], 1)} wk at observed cadence)"
        return f"{base} · n* {r.get('n_star')} · mean P&L/bet {mu:+.3f} · {reached}"
    return f"{base} · {st}: {r.get('reason', '')}"


def render(repo: Path, g: dict, p: dict, e: dict, now: datetime) -> str:
    L = [f"# MLB 2026 season look-back -- final read ({now:%Y-%m-%dT%H:%MZ})", "",
         "Generated by `scripts/mlb_season_lookback.py` (W80P.4). Read-only; no score is computed by this script -- each",
         "cell is read by the module that implements its own pre-registration. A cell below its judged n is reported as",
         "below n; its score is not read.", "",
         "## 1. MLB game markets (EXP-037 MLB) -- 2026 rows are never scored", "",
         f"Pre-registration: `{PREREGS['game'][0]}` -- {PREREGS['game'][1]}.", ""]
    if "error" in g:
        L += [f"UNAVAILABLE: calibration engine failed ({g['error']}).", ""]
    else:
        L += ["| cell | band | rows | settled games | status | verdict |", "|---|---|---|---|---|---|"]
        for c in g["cells"]:
            L.append(f"| {c['cell']} | {c['band']} | {c['rows']} | {c['settled_games']} | {c['status']} | "
                     f"{c['verdict'] or 'none (2026 rows never scored; first look = 150 settled 2027 games)'} |")
        if not g["cells"]:
            L.append("| (no MLB ledger found under exp_output/PREGAME_SHADOW) | | | | | |")
        L += ["", f"Source: calibration_engine.run(persist=False) at {g.get('generated')}.", ""]
    L += ["## 2. MLB player hits (KXMLBHIT) -- pre-game books T1/T2/T3 and T4M-PROJ (APR-0024 n*)", "",
          f"Pre-game: {PREREGS['hits_pregame'][0]} -- {PREREGS['hits_pregame'][1]}.",
          f"T4M-PROJ: {PREREGS['t4m_proj'][0]} -- {PREREGS['t4m_proj'][1]}.", ""]
    if "error" in p:
        L += [f"UNAVAILABLE: run_power_calc failed ({p['error']}); sources {p['sources']}.", ""]
    else:
        for band, r in p["bands"].items():
            L.append(f"- **{band}**: {_power_line(band, r)}")
        L += ["", f"Source: run_power_calc.run_all_bands({p['sources']}, alpha 0.05, power 0.95).", ""]
    L += ["## 3. Execution (T4M-PROJ and T1 demo fills; GG-527: fills only)", ""]
    if "error" in e:
        L += [f"UNAVAILABLE: {e['error']}", ""]
    else:
        for m in e["measures"]:
            val = m.get("value") if m.get("status") == "OK" else f"UNAVAILABLE ({m.get('reason')})"
            L.append(f"- **{m.get('id', m.get('measure', '?'))}**: {val} -- source {m.get('source')}, as of {m.get('as_of', 'n/a')}")
        L.append("")
    L += ["## 4. What the season proved", "",
          "Fill in from sections 1-3 only: a cell with a verdict in section 1 (none is possible from 2026 data), a band",
          "whose n* is REACHED in section 2 (sample adequacy only), and E1-E3. Everything else is 'below judged n'.", ""]
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--repo", default=str(REPO))
    ap.add_argument("--portfolio", default=None, help="default logs/paper_portfolio_mlb.json (box)")
    ap.add_argument("--t4-ledger", default=None, help="default logs/t4_mlb_resolved_ledger.jsonl")
    ap.add_argument("--out", default=None)
    a = ap.parse_args(argv)
    repo = Path(a.repo)
    pf = Path(a.portfolio) if a.portfolio else repo / "logs" / "paper_portfolio_mlb.json"
    t4 = Path(a.t4_ledger) if a.t4_ledger else repo / "logs" / "t4_mlb_resolved_ledger.jsonl"
    txt = render(repo, game_cells(repo), power(repo, pf, t4), execution(repo), datetime.now(timezone.utc))
    if a.out:
        Path(a.out).write_text(txt)
        print(f"wrote {a.out}")
    else:
        sys.stdout.write(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
