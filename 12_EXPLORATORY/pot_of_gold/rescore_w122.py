"""W122.2 Part A: pot-of-gold re-score on all archived data to date (addendum 1, 2026-11-20). Read-only on inputs.

  python 12_EXPLORATORY/pot_of_gold/rescore_w122.py --archive <PRICE_ARCHIVE> --settle <dir> --out 12_EXPLORATORY/pot_of_gold/out/w122

Step 1: measure.py's method unchanged (first two-sided pre-start snapshot per (ticker, tier); 70/30 split by game date per sport; entry
at the quote; exact fee; game-clustered), over every sport and family in the archive, props included -> cells.csv (+ summary.json).
Step 2: each of the 17 pre-registered cells is named against the 11-05 judged n, counted on FORWARD rows only (first snapshot at or after
2026-11-05): EARNED (forward Holm pass at judged n) / CLOSED (forward net mean <= 0 at judged n: "hypothesis closed, parked for R&D") /
IN_SAMPLE (below judged n: no score is read). Forward Holm is one-sided 5% across the cells at judged n, plus a bootstrap lower bound > 0.
Step 3: writes the candidate table to <out>/longshot_cells_w122.toml (copied to decision_trees/ by hand: the fence stops writes outside 12_EXPLORATORY). ONLY the 17 pre-registered cells may carry an orderable status; every other cell is written
IN_SAMPLE with its measured status kept in `measured_status`, so nothing routes from this window (addendum item 4).
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "longshot_bias"))
sys.path.insert(0, os.path.join(REPO, "src"))
import calib as C  # noqa: E402
import measure as M  # noqa: E402
from _fence import safe_out  # noqa: E402
from prediction_market_bot.quant import longshot_bias as L  # noqa: E402

try:
    import tomllib
except ImportError:  # the box is 3.9
    import tomli as tomllib  # type: ignore

FORWARD_FROM = C.parse_ts("2026-11-05T00:00:00Z")
JUDGED_N, JUDGED_GAMES, JUDGED_MINORITY = 150, 30, 5
CELLS_17 = os.path.join(REPO, "src", "prediction_market_bot", "decision_trees", "longshot_cells.toml")


def load17():
    with open(CELLS_17, "rb") as fh:
        return tomllib.load(fh)["cell"]


def forward_rows(archive, settle):
    rows = []
    for s in M.scan(archive):
        y = settle.get(s["ticker"])
        if y is None or s["ts"] < FORWARD_FROM:
            continue
        s["y"] = y
        s["bucket"] = L.pot_bucket(s["p"])
        s["book"] = "tight" if s["hs"] <= M.TIGHT else "wide"
        s["sport"] = M.sport_of(s["series"])
        rows.append(s)
    return rows


def name_17(rows):
    out, cand = [], []
    for c in load17():
        sel = [r for r in rows if r["series"] == c["family"] and r["tier"] == c["tier"] and r["bucket"] == c["bucket"]]
        e = L.evaluate_cell(sel, c["side"], boot=1000) if sel else {"n": 0, "games": 0}
        at_n = (e.get("n", 0) >= JUDGED_N and e.get("games", 0) >= JUDGED_GAMES and M.minority(e) >= JUDGED_MINORITY)
        rec = {"sport": c["sport"], "family": c["family"], "tier": c["tier"], "bucket": c["bucket"], "route": c["route"],
               "side": c["side"], "fwd_n": e.get("n", 0), "fwd_games": e.get("games", 0),
               "fwd_minority": round(M.minority(e), 1) if e.get("n") else 0, "at_judged_n": at_n}
        if at_n:  # no score below judged n (11-05 rule)
            rec.update(fwd_net=round(e["net_mean"], 4), fwd_lo=round(e["net_lo"], 4), p_one=e["p_one"])
            cand.append(rec)
        out.append(rec)
    rej = L.holm_one_sided([r["p_one"] for r in cand]) if cand else []
    holm = {id(r): rj for r, rj in zip(cand, rej)}
    for r in out:
        if not r["at_judged_n"]:
            r["verdict"] = "IN_SAMPLE"
        elif holm.get(id(r)) and r["fwd_lo"] > 0:
            r["verdict"] = "EARNED"
        elif r["fwd_net"] <= 0:
            r["verdict"] = "CLOSED (hypothesis closed, EXP-POT-17, parked for R&D)"
        else:
            r["verdict"] = "IN_SAMPLE (CONTINUE)"
    return out


def write_table(cells_csv, named, out_table):
    pre = {(r["family"], r["tier"], r["bucket"]): r for r in named}
    lines = ["# Pot-of-gold candidate table (W122.2). Generated by 12_EXPLORATORY/pot_of_gold/rescore_w122.py from the re-score of",
             "# 2026-11-20 (addendum 1). Only the 17 pre-registered cells can carry an orderable status; every other cell is IN_SAMPLE",
             "# with the measured status kept in measured_status. longshot.decide() gates on status, so this table routes nothing today.", ""]
    n = 0
    with open(cells_csv) as fh:
        for r in csv.DictReader(fh):
            if r["status"] == "UNTESTED" or r["route"] not in ("FADE_LONGSHOT", "TAKE_FAVOURITE", "BUY_LONGSHOT"):
                continue
            if r["book"] != "all":
                continue
            key = (r["family"], r["tier"], r["bucket"])
            reg = pre.get(key)
            is17 = bool(reg and reg["route"] == r["route"] and reg["side"] == r["side"])
            if is17:
                status = "HELD_OUT" if reg["verdict"] == "EARNED" else ("FAILED" if reg["verdict"].startswith("CLOSED") else "IN_SAMPLE")
            else:
                status = "IN_SAMPLE"
            lo = r["held_lo"] if r["held_lo"] != "" else (r["all_lo"] or "-1")
            nm = r["held_net"] if r["held_net"] != "" else "0"
            lines += ["[[cell]]", f'sport = "{r["sport"]}"', f'family = "{r["family"]}"', f'tier = "{r["tier"]}"',
                      f'bucket = "{r["bucket"]}"', 'book = "all"', f'route = "{r["route"]}"', f'side = "{r["side"]}"',
                      f'status = "{status}"', f'measured_status = "{r["status"]}"', f"preregistered = {str(is17).lower()}",
                      f"n = {int(r['all_n'] or 0)}", f"net_mean = {nm}", f"net_lo = {lo}", ""]
            n += 1
    with open(safe_out(out_table), "w") as fh:
        fh.write("\n".join(lines))
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--archive", required=True)
    ap.add_argument("--settle", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    out = os.path.abspath(a.out)
    saved, sys.argv = sys.argv, ["measure.py", "--archive", a.archive, "--settle", a.settle, "--out", out]
    try:
        M.main()  # in-process: the fence forbids subprocess
    finally:
        sys.argv = saved
    settle = C.load_settlements(a.settle)
    named = name_17(forward_rows(a.archive, settle))
    with open(safe_out(os.path.join(out, "named_17.json")), "w") as fh:
        json.dump(named, fh, indent=1)
    n_t = write_table(os.path.join(out, "cells.csv"), named, os.path.join(out, "longshot_cells_w122.toml"))
    tally = defaultdict(int)
    for r in named:
        tally[r["verdict"]] += 1
    print(json.dumps({"named_17": dict(tally), "table_cells": n_t,
                      "forward_n_by_cell": {f"{r['family']}/{r['tier']}/{r['bucket']}": [r["fwd_n"], r["fwd_games"]] for r in named}}, indent=1))


if __name__ == "__main__":
    main()
